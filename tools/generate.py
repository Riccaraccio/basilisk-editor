#!/usr/bin/env python3
"""
Generates the editor files' language knowledge from spec/language.json.

    python3 tools/generate.py           update the files
    python3 tools/generate.py --check   exit 1 if any file is out of date

Text files carry a block between "GENERATED by tools/generate.py" and
"END GENERATED" marker lines (in the file's comment syntax); only that
block is rewritten. The VS Code injection grammar is JSON (no comments):
its "keywords" repository entry is rewritten instead.
"""
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SPEC = os.path.join(ROOT, "spec", "language.json")
BEGIN = "GENERATED by tools/generate.py from spec/language.json -- do not edit"
END = "END GENERATED"


def load_spec():
    with open(SPEC, encoding="utf-8") as f:
        return json.load(f)


def words(spec, cat):
    return list(spec["highlight"][cat].get("words", []))


def prefixes(spec, cat):
    return list(spec["highlight"][cat].get("prefixes", []))


def literals(spec, cat):
    return list(spec["highlight"][cat].get("literals", []))


# ---------------------------------------------------------------------------
# Detection regular expression, in three dialects.
#
#   ^\s*( event\s+ID\s*\(
#       | #\s*include\s*"(PREFIX|...)[/.]
#       | ((QUALIFIER)\s+)?(FIELDTYPE)\s+\*?\s*ID\s*\[\]
#       | (LOOP|LOOPPREFIX\w+)\s*\( )

class Dialect:
    def __init__(self, grp, alt, ws, w, ident, lparen, star, brackets, bol):
        self.grp, self.alt, self.ws, self.w = grp, alt, ws, w
        self.ident, self.lparen, self.star, self.brackets, self.bol = ident, lparen, star, brackets, bol

    def any(self, items):
        return self.grp(self.alt.join(items))


VIM = Dialect(grp=lambda s: "%(" + s + ")", alt="|", ws=r"\s", w=r"\w", ident=r"\w+",
              lparen=r"\(", star=r"\*", brackets=r"\[\]", bol="^")
JS = Dialect(grp=lambda s: "(?:" + s + ")", alt="|", ws=r"\s", w=r"\w", ident=r"\w+",
             lparen=r"\(", star=r"\*", brackets=r"\[\]", bol="^")
ELISP = Dialect(grp=lambda s: r"\(?:" + s + r"\)", alt=r"\|", ws="[ \t]", w="[A-Za-z0-9_]",
                ident="[A-Za-z_][A-Za-z0-9_]*", lparen="(", star=r"\*", brackets=r"\[\]", bol="^")


def detect_regex(spec, d):
    det = spec["detect"]
    ws = d.ws
    loops = [re.escape(x) for x in words(spec, "loop")]
    loops += [re.escape(p) + d.w + "+" for p in prefixes(spec, "loop")]
    alts = [
        "event" + ws + "+" + d.ident + ws + "*" + d.lparen,
        "#" + ws + "*include" + ws + '*"' + d.any(det["include_prefixes"]) + "[/.]",
        d.grp(d.any(det["field_qualifiers"]) + ws + "+") + "?" + d.any(det["field_types"])
        + ws + "+" + d.star + "?" + ws + "*" + d.ident + ws + "*" + d.brackets,
        d.any(loops) + ws + "*" + d.lparen,
    ]
    return d.bol + ws + "*" + d.any(alts)


# ---------------------------------------------------------------------------
# Generators: each returns the lines between the markers.

def gen_vim_syntax(spec):
    def kw(group, ws):
        return f"syn keyword {group:<18}{' '.join(ws)}" if ws else None

    loop = [r"\<" + w + r"\>" for w in words(spec, "loop")]
    loop += [r"\<" + p + r"\w\+\>" for p in prefixes(spec, "loop")]
    out = [
        f'syn match   {"basiliskRepeat":<18}"' + r"\%(" + r"\|".join(loop) + r"\)" + '"',
        kw("basiliskStatement", words(spec, "statement")),
        f'syn match   {"basiliskEventCond":<18}"' + r"\%(^event\s.*\)\@<=\<\%("
        + r"\|".join(words(spec, "event_condition")) + r"\)\>" + '"',
        kw("basiliskType", words(spec, "type")),
        kw("basiliskStorage", words(spec, "qualifier")),
    ]
    out += [f'syn match   {"basiliskStorage":<18}"{lit}"' for lit in literals(spec, "qualifier")]
    out += [
        kw("basiliskOperator", words(spec, "operator")),
        kw("basiliskBuiltin", words(spec, "builtin")),
        kw("basiliskConstant", words(spec, "constant")),
        kw("basiliskFunction", words(spec, "function")),
    ]
    return [x for x in out if x]


def gen_vim_ftdetect(spec):
    pat = r"\v" + detect_regex(spec, VIM)
    return [f"let s:basilisk_pattern = '{pat}'",
            f"let s:basilisk_max_lines = {spec['detect']['max_lines']}"]


def nano_alt(ws):
    return "|".join(re.escape(w) for w in ws)


def gen_nano(spec):
    loop = words(spec, "loop") + [p + "[[:alnum:]_]+" for p in prefixes(spec, "loop")]
    lits = "".join("|" + re.escape(lit) for lit in literals(spec, "qualifier"))
    return [
        "# Basilisk loops, events and reductions (event conditions: see spec).",
        'color brightmagenta "\\<(' + "|".join(loop + words(spec, "statement")) + ')\\>"',
        "# Basilisk types, qualifiers and operators.",
        'color brightgreen "\\<(' + nano_alt(words(spec, "type")) + ')\\>"',
        'color brightgreen "\\<(' + nano_alt(words(spec, "qualifier") + words(spec, "operator"))
        + ')\\>' + lits + '"',
        "# Basilisk built-in variables, boundaries and boundary conditions.",
        'color cyan "\\<(' + nano_alt(words(spec, "builtin") + words(spec, "constant")) + ')\\>"',
        'color cyan "\\<(' + nano_alt(words(spec, "function")) + ')\\>"',
    ]


def tm_alt(ws):
    return "|".join(re.escape(w) for w in ws)


def gen_vscode_keywords(spec):
    loop = [re.escape(w) for w in words(spec, "loop")]
    loop += [re.escape(p) + r"\w+" for p in prefixes(spec, "loop")]
    lits = "".join("|" + re.escape(lit) for lit in literals(spec, "qualifier"))
    return {"patterns": [
        {"match": r"\b(" + "|".join(loop) + r")\b", "name": "keyword.control.loop.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "statement")) + r")\b", "name": "keyword.control.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "type")) + r")\b", "name": "storage.type.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "qualifier")) + r")\b" + lits,
         "name": "storage.modifier.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "operator")) + r")\b", "name": "keyword.operator.new.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "builtin")) + r")\b", "name": "variable.language.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "constant")) + r")\b", "name": "constant.language.basilisk"},
        {"match": r"\b(" + tm_alt(words(spec, "function")) + r")\b(?=\s*\()",
         "name": "support.function.basilisk"},
        # not word lists: component accesses u.x and empty stencils s[]
        {"match": r"(?<=[\w\]])\.(x|y|z|n|t)\b", "name": "variable.other.member.component.basilisk"},
        {"match": r"\[\]", "name": "punctuation.stencil.basilisk keyword.operator.stencil.basilisk"},
    ]}


def gen_js(spec):
    pat = detect_regex(spec, JS)
    return [f"const PATTERN = new RegExp({json.dumps(pat)}, 'm');",
            f"const MAX_LINES = {spec['detect']['max_lines']};"]


def el_str(s):
    """Emacs Lisp string literal (tabs written as \\t)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def el_or(ws):
    return "(or " + " ".join(el_str(w) for w in ws) + ")"


def gen_elisp(spec):
    loop = [el_str(w) for w in words(spec, "loop")]
    loop += [f"(seq {el_str(p)} (+ (any alnum \"_\")))" for p in prefixes(spec, "loop")]
    quals = el_or(words(spec, "qualifier") + words(spec, "operator"))
    lits = " ".join(el_str(lit) for lit in literals(spec, "qualifier"))
    return [
        ";;;###autoload",
        "(defconst basilisk--detect-regexp",
        "  " + el_str(detect_regex(spec, ELISP)),
        '  "Regexp matching a line which only appears in Basilisk C.")',
        ";;;###autoload",
        f"(defconst basilisk--detect-max-lines {spec['detect']['max_lines']})",
        "",
        "(defconst basilisk-font-lock-keywords",
        "  `((,(rx bol (group \"event\") (+ blank) (group (any alpha \"_\") (* (any alnum \"_\"))))",
        "     ;; override: cc-mode takes \"event init\" for a declaration",
        "     (1 font-lock-keyword-face t) (2 font-lock-function-name-face t))",
        "    (,(rx bol \"event\" (+ blank) (* nonl) symbol-start (group "
        + el_or(words(spec, "event_condition")) + ") symbol-end)",
        "     (1 font-lock-constant-face))",
        "    (,(rx symbol-start (or " + " ".join(loop) + " "
        + " ".join(el_str(w) for w in words(spec, "statement")) + ") symbol-end)",
        "     . font-lock-keyword-face)",
        "    (,(rx symbol-start " + el_or(words(spec, "type")) + " symbol-end)",
        "     . font-lock-type-face)",
        "    (,(rx (or (seq symbol-start " + quals + " symbol-end) " + lits + "))",
        "     . font-lock-keyword-face)",
        "    (,(rx symbol-start " + el_or(words(spec, "builtin")) + " symbol-end)",
        "     . font-lock-builtin-face)",
        "    (,(rx symbol-start " + el_or(words(spec, "constant")) + " symbol-end)",
        "     . font-lock-constant-face)",
        "    (,(rx symbol-start " + el_or(words(spec, "function")) + " symbol-end (* blank) \"(\")",
        "     . font-lock-builtin-face))",
        '  "Basilisk additions to the C font-lock keywords.")',
    ]


def gen_python(spec):
    out = ["# kind, signature, markdown documentation of built-in Basilisk constructs",
           "BUILTINS = {"]
    for name, d in spec["docs"].items():
        out.append(f"    {json.dumps(name)}: ({json.dumps(d['kind'])}, {json.dumps(d['sig'], ensure_ascii=False)},")
        out.append(f"        {json.dumps(d['doc'], ensure_ascii=False)}),")
    out.append("}")
    out.append("")
    out.append("SNIPPETS = {")
    for name, s in spec["snippets"].items():
        out.append(f"    {json.dumps(name)}: {json.dumps(s, ensure_ascii=False)},")
    out.append("}")
    return out


# ---------------------------------------------------------------------------

TARGETS = [  # (path, comment prefix, generator)
    ("syntax/basilisk.vim", '"', gen_vim_syntax),
    ("ftdetect/basilisk.vim", '"', gen_vim_ftdetect),
    ("nano/basilisk.nanorc", "#", gen_nano),
    ("vscode/extension.js", "//", gen_js),
    ("basilisk-editor.el", ";;", gen_elisp),
    ("server/basilisk_lsp.py", "#", gen_python),
]
JSON_TARGETS = [
    ("vscode/syntaxes/basilisk-injection.tmLanguage.json", ("repository", "keywords"), gen_vscode_keywords),
]


def render_text(path, comment, lines):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        text = f.read()
    pat = re.compile(r"(^[ \t]*" + re.escape(comment) + r" " + re.escape(BEGIN) + r"\n)(.*?)(^[ \t]*"
                     + re.escape(comment) + r" " + re.escape(END) + r"[ \t]*$)", re.M | re.S)
    if not pat.search(text):
        sys.exit(f"{path}: no '{comment} {BEGIN}' ... '{comment} {END}' block")
    body = "".join(l + "\n" for l in lines)
    return text, pat.sub(lambda m: m.group(1) + body + m.group(3), text, count=1)


def render_json(path, keys, value):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        text = f.read()
    data = json.loads(text)
    node = data
    for k in keys[:-1]:
        node = node[k]
    node[keys[-1]] = value
    return text, json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main(argv):
    check = "--check" in argv
    spec = load_spec()
    stale = []
    jobs = [(p, render_text(p, c, g(spec))) for p, c, g in TARGETS]
    jobs += [(p, render_json(p, k, g(spec))) for p, k, g in JSON_TARGETS]
    for path, (old, new) in jobs:
        if old != new:
            stale.append(path)
            if not check:
                with open(os.path.join(ROOT, path), "w", encoding="utf-8") as f:
                    f.write(new)
    if check:
        if stale:
            print("out of date (run python3 tools/generate.py):\n  " + "\n  ".join(stale))
            return 1
        print("generated files are up to date")
        return 0
    print("updated: " + (", ".join(stale) if stale else "nothing (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
